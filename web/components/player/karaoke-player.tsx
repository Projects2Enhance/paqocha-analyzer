// Generated by data/scripts/ — see ../../../data/README.md. Never written
// to by the app; regenerated offline, by hand, when the raw corpus changes.
const SEARCH_INDEX_PATH = "/data/search-index.json";
const CLIPS_BASE_PATH = "/data/clips";
// Provisional: a flat folder of every mp3, filled in by hand for now (see
// web/public/data/audios/) — stands in for the real S3-backed audio
// hosting that'll eventually replace it. Only `audio_file` (from each
// clip's own metadata) is ever appended to this, never anything
// user-supplied.
const AUDIOS_BASE_PATH = "/data/audios";
// Caps how many matched clips get fetched/shown per search. Checked
// against the real generated index: most words occur in only a handful of
// clips (median 1, p90 4 across the 7541 indexed words), but common
// grammatical words can occur in 200+ (e.g. "mana", 217) — fetching every
// one of those on a single search isn't reasonable yet. [TO BE DEFINED]:
// real pagination/relevance ranking once this needs to scale past a flat
// cap with no "+N more" affordance.
const MAX_MATCHES = 24;
// How many words of lead-in before the first search match to start
// playback from, so the clip doesn't open mid-sentence right on the word.
const MATCH_LEAD_IN_WORDS = 3;
// Artificial minimum wait before revealing real content, simulating a
// search request — the actual fetches (static local JSON) resolve far
// faster than this. See web/DESIGN.md -> Components -> KaraokePlayer.
const SIMULATED_SEARCH_DELAY_MS = 3000;

// Finds the last word whose start time has passed — words are sorted
// ascending, so once we pass `time` we can stop. Keeps the current word
// highlighted through any silence gap until the next word actually starts.
function findActiveWordIndex(words: AlignmentWord[], time: number): number {
  let active = -1;
  for (const word of words) {
    if (word.start <= time) {
      active += 1;
    } else {
      break;
    }
  }
  return active;
}

// Lowercases and strips leading/trailing punctuation (keeps internal
// characters, e.g. the hyphen in "ayllu-ayllunta") so a search term and a
// transcript word compare equal regardless of trailing commas/periods.
function normalizeWord(word: string): string {
  return word.toLowerCase().replace(/^[^\p{L}]+|[^\p{L}]+$/gu, "");
}

// Every word index within one already-fetched clip's alignment whose
// normalized text equals the normalized query — used both to decide which
// words to highlight in that clip's transcript and where to seek to.
// Which clips are considered *at all* comes from the real search-index.json
// lookup in the effect below, not from scanning transcripts here.
function findSearchMatches(words: AlignmentWord[], query: string | undefined): number[] {
  const normalizedQuery = query ? normalizeWord(query) : "";
  if (!normalizedQuery) return [];
  const indices: number[] = [];
  words.forEach((word, index) => {
    if (normalizeWord(word.word) === normalizedQuery) indices.push(index);
  });
  return indices;
}

// Start MATCH_LEAD_IN_WORDS words before the first match, or 0 if the term
// doesn't occur in this transcript at all.
function computeInitialSeekTime(
  words: AlignmentWord[],
  matchIndices: number[],
): number {
  if (matchIndices.length === 0) return 0;
  const startIndex = Math.max(0, matchIndices[0] - MATCH_LEAD_IN_WORDS);
  return words[startIndex].start;
}

// Real search against the generated dataset (see ../../../data/README.md
// for how search-index.json/clips/<id>.json are built) — see
// web/DESIGN.md -> Components -> KaraokePlayer for the full write-up. The
// query is normalized and looked up in the search index for the matching
// audio_ids (capped at MAX_MATCHES), then each matched clip's combined
// JSON — metadata, real forced-alignment word timestamps, and a
// word-by-word morphosyntactic breakdown — is fetched. If the term
// doesn't occur in any transcript at all, the whole player body is
// replaced by NoResultsState instead of showing an empty transcript/match
// list.
export function KaraokePlayer() {
  const searchParams = useSearchParams();
  // Initial value only — see handleInPageSearch below for why this isn't
  // re-read from searchParams on every render.
  const [activeQuery, setActiveQuery] = useState(() =>
    searchParams.get("q")?.trim(),
  );

  const [searchIndex, setSearchIndex] = useState<SearchIndex | null>(null);
  // Bundles the matched clips together with the query they're an answer
  // for — null until the first resolution. Keeping `query` alongside
  // `clips` (rather than a separate `[clips, setClips]`) is what lets
  // `isCurrentQueryResolved` below tell "these are real results for the
  // current search" apart from "these are the previous search's results,
  // still sitting here while a new fetch is in flight" — both set together,
  // once, from inside the fetch effect's resolved callback below.
  const [resolved, setResolved] = useState<{
    query: string | undefined;
    clips: ClipData[];
  } | null>(null);
  const [loadError, setLoadError] = useState(false);

  const [isPlaying, setIsPlaying] = useState(false);
  const [currentTime, setCurrentTime] = useState(0);
  const [duration, setDuration] = useState(0);
  const [view, setView] = useState<ResultsView>("list");
  const [activeMatchIndex, setActiveMatchIndex] = useState(0);
  const [minLoadingElapsed, setMinLoadingElapsed] = useState(false);
  const [isSearchOpen, setIsSearchOpen] = useState(false);

  const audioRef = useRef<HTMLAudioElement>(null);

  // Depends on `activeQuery`, not `[]`: an in-page re-search (see
  // handleInPageSearch) resets `minLoadingElapsed` to false in its own event
  // handler, and this effect re-arms the same timer, so the skeleton phase
  // plays again for every search, not just the first one.
  useEffect(() => {
    const timeoutId = setTimeout(
      () => setMinLoadingElapsed(true),
      SIMULATED_SEARCH_DELAY_MS,
    );
    return () => clearTimeout(timeoutId);
  }, [activeQuery]);

  // The search index doesn't depend on the query — load it once, on mount,
  // and never again.
  useEffect(() => {
    let cancelled = false;
    fetch(SEARCH_INDEX_PATH)
      .then((res) => res.json())
      .then((index: SearchIndex) => {
        if (!cancelled) setSearchIndex(index);
      })
      .catch(() => {
        if (!cancelled) setLoadError(true);
      });
    return () => {
      cancelled = true;
    };
  }, []);

  // Resolves `activeQuery` against `searchIndex` and fetches every matched
  // clip, every time either changes — covers both the first load (once
  // `searchIndex` arrives) and an in-page re-search (`activeQuery`
  // changing instead, once the index is already cached). Deliberately
  // doesn't clear `resolved` synchronously up front while the new fetch is
  // in flight (a plain `setResolved(null)` at the top of this effect body
  // would be exactly the cascading-render pattern react-hooks/
  // set-state-in-effect flags) — `isCurrentQueryResolved` below achieves
  // the same "don't show/act on stale results" effect by comparing the
  // query `resolved` already holds against the current one, during render,
  // instead of clearing state to force it.
  useEffect(() => {
    if (!searchIndex) return;
    let cancelled = false;

    const normalized = activeQuery ? normalizeWord(activeQuery) : "";
    const matchIds = (normalized ? searchIndex[normalized] : undefined) ?? [];

    Promise.all(
      matchIds
        .slice(0, MAX_MATCHES)
        .map((id) => fetch(`${CLIPS_BASE_PATH}/${id}.json`).then((res) => res.json())),
    )
      .then((fetchedClips: ClipData[]) => {
        if (cancelled) return;
        setResolved({ query: activeQuery, clips: fetchedClips });
        setActiveMatchIndex(0);
      })
      .catch(() => {
        if (!cancelled) setLoadError(true);
      });

    return () => {
      cancelled = true;
    };
  }, [searchIndex, activeQuery]);

  // `resolved` can legitimately still hold the *previous* query's results
  // for a moment after `activeQuery` changes (the fetch above hasn't
  // resolved yet) — checking `resolved.query` against the current
  // `activeQuery`, not just whether `resolved` exists, is what keeps that
  // stale clip from briefly being treated as "the" active clip (and its
  // <audio> seeking/autoplaying) under the new query.
  // `resolved !== null` is checked explicitly, not just `resolved?.query
  // === activeQuery` — both sides would otherwise be `undefined` and
  // compare equal before anything has ever resolved, for the no-query case.
  const isCurrentQueryResolved =
    resolved !== null && resolved.query === activeQuery;
  const clips = isCurrentQueryResolved ? resolved!.clips : null;
  const matchCount = clips?.length ?? 0;
  const activeClip =
    matchCount > 0 ? clips![Math.min(activeMatchIndex, matchCount - 1)] : null;

  useEffect(() => {
    const audio = audioRef.current;
    if (!audio || !activeClip) return;

    const initialTime = computeInitialSeekTime(
      activeClip.alignment.word_segments,
      findSearchMatches(activeClip.alignment.word_segments, activeQuery),
    );

    function applyInitialTime() {
      if (!audio) return;
      audio.currentTime = initialTime;
      setCurrentTime(initialTime);
    }

    // Tried immediately (works once the browser already has metadata
    // cached) and reapplied on "loadedmetadata" — setting currentTime
    // before duration is known can silently get reset once it loads.
    applyInitialTime();
    // Defensive: if duration somehow is already known the instant this
    // runs, pick it up immediately rather than only from "loadedmetadata"
    // below (which won't fire again if it already fired once, missed).
    if (!Number.isNaN(audio.duration)) setDuration(audio.duration);
    // Autoplays on every fresh load/match switch — requested on purpose:
    // landing on a search-match lead-in that's still paused read as
    // broken. `.catch()` swallows a rejected autoplay promise (blocked by
    // the browser's autoplay policy) rather than an uncaught rejection;
    // worst case it just stays paused at the right position, same as
    // before this existed.
    audio.play().catch(() => {});

    const handleTimeUpdate = () => setCurrentTime(audio.currentTime);
    const handleLoadedMetadata = () => {
      setDuration(audio.duration);
      applyInitialTime();
    };
    const handlePlay = () => setIsPlaying(true);
    const handlePause = () => setIsPlaying(false);

    audio.addEventListener("timeupdate", handleTimeUpdate);
    audio.addEventListener("loadedmetadata", handleLoadedMetadata);
    audio.addEventListener("play", handlePlay);
    audio.addEventListener("pause", handlePause);
    // "ended" doesn't reliably also fire "pause" per the HTML spec, so
    // isPlaying would otherwise stay stuck true once playback reaches the end.
    audio.addEventListener("ended", handlePause);
    return () => {
      audio.removeEventListener("timeupdate", handleTimeUpdate);
      audio.removeEventListener("loadedmetadata", handleLoadedMetadata);
      audio.removeEventListener("play", handlePlay);
      audio.removeEventListener("pause", handlePause);
      audio.removeEventListener("ended", handlePause);
      // Stops playback whenever this cleanup runs, not only on unmount —
      // also on every `activeClip` change, i.e. a new in-page search or
      // switching matches (see handleInPageSearch/selectMatch below): a
      // brief, synchronous pause right before the new run's own
      // `audio.play()` a few lines up, not a perceptible gap. The unmount
      // case (e.g. navigating back to "/" via the back button) is still
      // the main reason this exists: removing an <audio> element from the
      // DOM doesn't reliably stop it immediately in every browser — a
      // real bug, not a demo-data shortcut — so it's paused directly here
      // rather than relying on implicit cleanup.
      audio.pause();
    };
    // `activeClip` reruns this whole effect both on a brand-new search
    // resolving its first match and on switching matches via
    // previous/next/the sidebar list (`selectMatch` below) — same
    // seek-to-lead-in + autoplay + (re)attach-listeners behavior either
    // way, just keyed on which clip is active instead of a single fixed
    // alignment. `activeQuery` is listed too since `findSearchMatches`
    // reads it directly inside this effect. `minLoadingElapsed` is a
    // dependency for a different reason, not just a formality: the <audio>
    // element itself only mounts once `isReady` (which needs it) is true —
    // see the render below — so `audioRef.current` can still be null the
    // moment `clips` first resolves, well before the simulated delay
    // elapses. Without this in the deps, the effect would hit the `!audio`
    // early return once and never re-run once <audio> actually exists a
    // few seconds later, and silently never attach any listeners at all —
    // audio would still play (the transport buttons call
    // `audioRef.current.play()` directly), just with the transcript/seek
    // bar/Analysis never updating, since nothing was listening for
    // "timeupdate". This was a real bug the first time this existed, not a
    // hypothetical.
  }, [activeClip, activeQuery, minLoadingElapsed]);

  function seekTo(time: number, autoplay = false) {
    const audio = audioRef.current;
    if (!audio) return;
    audio.currentTime = time;
    setCurrentTime(time);
    if (autoplay) audio.play();
  }

  function handleTogglePlay() {
    const audio = audioRef.current;
    if (!audio) return;
    if (audio.paused) audio.play();
    else audio.pause();
  }

  // Re-searching *from* the player (the new magnifying-glass button in the
  // header, not SearchBar on "/") deliberately does *not* repeat the
  // full-navigation pattern documented above for Home <-> player — that
  // pattern exists to dodge Next's router-cache state leaks *across
  // routes*; this never leaves "/search" at all. Updating `activeQuery`
  // (plain React state) is enough to re-trigger the search-index lookup +
  // clip-refetch effect above, exactly as if this were a fresh mount with
  // a different "?q=" — the search index itself doesn't need refetching,
  // since it doesn't depend on the query. `window.history.replaceState`,
  // not a Next.js navigation of any kind (no `router.push`, no `<Link>`),
  // keeps the address bar honest without asking Next's router to do
  // anything at all.
  function handleInPageSearch(term: string) {
    const sanitized = term.replace(/\s+/g, "");
    if (!sanitized) return;
    setActiveQuery(sanitized);
    setActiveMatchIndex(0);
    // Replays the same simulated-search skeleton phase as the first load
    // (see the `minLoadingElapsed` effect above) instead of snapping
    // straight to the new result.
    setMinLoadingElapsed(false);
    window.history.replaceState(
      null,
      "",
      `/search?q=${encodeURIComponent(sanitized)}`,
    );
    setIsSearchOpen(false);
  }

  if (loadError) {
    return (
      <PageShell
        query={activeQuery}
        onOpenSearch={() => setIsSearchOpen(true)}
      >
        <p style={{ color: "var(--color-text-muted)" }}>
          Couldn&apos;t load search results. Try refreshing.
        </p>
      </PageShell>
    );
  }

  // Gates on the simulated delay too, not just the (near-instant, local)
  // fetches — see SIMULATED_SEARCH_DELAY_MS above.
  const isReady = isCurrentQueryResolved && minLoadingElapsed;

  const activeWordIndex = activeClip
    ? findActiveWordIndex(activeClip.alignment.word_segments, currentTime)
    : -1;
  const searchMatchIndices = activeClip
    ? findSearchMatches(activeClip.alignment.word_segments, activeQuery)
    : [];

  // Blocks the whole player body once the search has actually resolved
  // (`isReady`) and found nothing — including an empty query (a direct
  // "/search" visit with no "?q="): with real, per-query data there's no
  // fallback "example" clip left to fall through to the way there used to
  // be, so an empty query is just another kind of empty result now.
  const noResults = isReady && matchCount === 0;

  // The effect above re-seeks/autoplays once the newly active clip's own
  // <audio> (a different src now, not just a different position in the
  // same file) is ready, so this doesn't need to seek itself the way it
  // did back when every match pointed at the same one audio file.
  function selectMatch(index: number) {
    setActiveMatchIndex(index);
  }

  return (
    <PageShell query={activeQuery} onOpenSearch={() => setIsSearchOpen(true)}>
      {noResults ? (
        <NoResultsState query={activeQuery} />
      ) : (
        <div className="flex flex-1 min-h-0 flex-col lg:flex-row gap-5 lg:gap-6 px-5 sm:px-8 pb-5 sm:pb-8 overflow-hidden">
          <div className="flex flex-col min-h-0 flex-1 gap-4">
            {isReady && activeClip ? (
              <KaraokeTranscript
                segments={activeClip.alignment.segments}
                activeWordIndex={activeWordIndex}
                matchWordIndices={searchMatchIndices}
                onWordClick={(time) => seekTo(time)}
              />
            ) : (
              <TranscriptSkeleton />
            )}
            <AudioPlayerControls
              isPlaying={isPlaying}
              currentTime={currentTime}
              duration={duration}
              onTogglePlay={handleTogglePlay}
              onSeek={(time) => seekTo(time)}
              onPrevious={() => selectMatch(activeMatchIndex - 1)}
              onNext={() => selectMatch(activeMatchIndex + 1)}
              canGoPrevious={activeMatchIndex > 0}
              canGoNext={activeMatchIndex < matchCount - 1}
            />
          </div>

          <div className="flex flex-col min-h-0 max-h-[38vh] lg:max-h-none lg:h-full lg:w-[320px] flex-shrink-0 gap-3">
            <ViewSwitch value={view} onChange={setView} />
            {view === "list" ? (
              isReady && clips ? (
                <div className="flex flex-col gap-3 min-h-0 overflow-y-auto paqocha-scroll paqocha-reveal-fade">
                  {clips.map((clip, index) => (
                    <MatchCard
                      key={clip.metadata.audio_id}
                      metadata={clip.metadata}
                      isActive={index === activeMatchIndex}
                      isPlaying={isPlaying}
                      onSelect={() => selectMatch(index)}
                    />
                  ))}
                </div>
              ) : (
                <div className="flex flex-col gap-3 min-h-0 overflow-y-auto">
                  <MatchCardSkeleton />
                </div>
              )
            ) : isReady && activeClip ? (
              <WordAnalysis
                words={activeClip.wordAnalysis.words}
                activeWordIndex={activeWordIndex}
                isPlaying={isPlaying}
              />
            ) : (
              <WordAnalysisSkeleton />
            )}
          </div>
        </div>
      )}

      <style>{MATCH_CARD_STYLES}</style>
      <style>{SKELETON_STYLES}</style>

      {isReady && activeClip && !noResults && (
        <audio
          ref={audioRef}
          src={`${AUDIOS_BASE_PATH}/${activeClip.metadata.audio_file}`}
          preload="auto"
        />
      )}

      <PlayerSearchOverlay
        isOpen={isSearchOpen}
        onClose={() => setIsSearchOpen(false)}
        onSubmit={handleInPageSearch}
      />
    </PageShell>
  );
}

function PageShell({
  query,
  onOpenSearch,
  children,
}: {
  query: string | undefined;
  onOpenSearch: () => void;
  children: ReactNode;
}) {
  return (
    <div
      style={{
        position: "fixed",
        inset: 0,
        display: "flex",
        flexDirection: "column",
        background: "var(--color-bg)",
        color: "var(--color-text)",
      }}
    >
      <div className="flex flex-col flex-1 min-h-0 w-full max-w-[1240px] mx-auto">
        <header className="flex flex-col gap-3 px-5 sm:px-8 pt-5 sm:pt-7 pb-4">
          <div className="flex items-center justify-between">
            {/* Plain <a>, not next/link's <Link> — a full navigation on
                purpose, see the long comment on SearchBar's handleSearch. */}
            {/* eslint-disable-next-line @next/next/no-html-link-for-pages --
                deliberate: see the comment above. */}
            <a
              href="/"
              aria-label="Back to home"
              className="paqocha-icon-button"
              style={{
                display: "inline-flex",
                alignItems: "center",
                justifyContent: "center",
                width: "2.75rem",
                height: "2.75rem",
                borderRadius: "999px",
                background: "var(--color-primary)",
                color: "var(--color-on-primary)",
              }}
            >
              <BackArrowIcon size={18} />
            </a>

            <div className="flex items-center gap-2">
              <button
                type="button"
                onClick={onOpenSearch}
                aria-label="Search"
                className="paqocha-icon-button"
                style={{
                  display: "inline-flex",
                  alignItems: "center",
                  justifyContent: "center",
                  width: "2.75rem",
                  height: "2.75rem",
                  borderRadius: "999px",
                  border: "none",
                  background: "var(--color-primary)",
                  color: "var(--color-on-primary)",
                  cursor: "pointer",
                }}
              >
                <SearchIcon size={18} />
              </button>

              <ThemeToggle />
            </div>
          </div>

          <h1
            style={{
              margin: 0,
              fontSize: "clamp(1.5rem, 3.4vw, 2.1rem)",
              fontWeight: 700,
            }}
          >
            {query ? `“${query}”` : "Search"}
          </h1>
        </header>

        {children}
      </div>

      <style>{`
        /* Shared by the back link and the new search trigger — both are
           plain filled --color-primary circles with identical hover/press
           feedback, so one class covers both instead of two near-duplicate
           ones. (ThemeToggle keeps its own equivalent rules under its own
           class name, self-contained on purpose — see its own file.) */
        .paqocha-icon-button {
          transition: filter 160ms ease, transform 120ms ease;
        }

        .paqocha-icon-button:hover {
          filter: brightness(1.08);
        }

        .paqocha-icon-button:active {
          transform: scale(0.94);
        }
      `}</style>
    </div>
  );
}
